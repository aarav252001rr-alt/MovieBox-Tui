from typing import Protocol, Any

class Provider(Protocol):
    async def search(self, q: str, content_type: str = "all") -> dict[str, Any]: ...
    async def details(self, item_id: str, content_type: str) -> dict[str, Any]: ...
    async def sources(self, item_id: str, content_type: str = "movie") -> dict[str, Any]: ...
